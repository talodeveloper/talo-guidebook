// ─── Google Fonts loader (cached by link id) ──────────────────────────────────
const loadedFonts = new Set()
function loadGoogleFont(url, id) {
  if (!url || loadedFonts.has(id)) return
  loadedFonts.add(id)
  const link = document.createElement('link')
  link.id = id
  link.rel = 'stylesheet'
  link.href = url
  document.head.appendChild(link)
}

// ─── Inject CSS vars onto document root ───────────────────────────────────────
export function injectTheme(themeKey, isNight) {
  const theme = THEMES[themeKey] || THEMES.modern
  const vars = isNight ? { ...theme.day, ...theme.night } : theme.day
  const root = document.documentElement

  Object.entries(vars).forEach(([k, v]) => root.style.setProperty(k, v))

  // Per-theme fonts
  const { heading, body, googleUrl } = theme.fonts || {}
  if (googleUrl) loadGoogleFont(googleUrl, `gfont-${themeKey}`)
  root.style.setProperty('--t-font-heading', heading ? `'${heading}', serif` : 'inherit')
  root.style.setProperty('--t-font-body',    body    ? `'${body}', sans-serif` : 'inherit')

  // Body background for starfield / milky-way themes
  if (isNight && theme.nightEffect) {
    document.body.dataset.nightEffect = theme.nightEffect
    document.body.style.background = '#000'
  } else {
    delete document.body.dataset.nightEffect
    document.body.style.background = ''
  }
}
